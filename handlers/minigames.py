@router.message(Command("rps", "кнб", "каменьножницыбумага"))
async def cmd_rps(message: Message, command: CommandObject):
    uid = message.from_user.id if message.from_user else 0
    now = time.monotonic()
    if now - _rps_cd[uid] < 1.5:
        await message.reply(fail("Подожди секунду и сыграй снова."))
        return
    _rps_cd[uid] = now
    choice = (command.args or "").strip().lower()
    map_ = {
        "к": "камень", "камень": "камень", "rock": "камень", "stone": "камень",
        "н": "ножницы", "ножницы": "ножницы", "scissors": "ножницы",
        "б": "бумага", "бумага": "бумага", "paper": "бумага",
    }
    if choice not in map_:
        await message.reply(
            card(
                "Камень · Ножницы · Бумага",
                "Напиши: <code>/rps камень</code> · <code>/rps ножницы</code> · <code>/rps бумага</code>\n"
                "Коротко: <code>/rps к</code> · <code>/rps н</code> · <code>/rps б</code>",
                emoji="✂️",
            )
        )
        return
    user = map_[choice]
    bot = random.choice(["камень", "ножницы", "бумага"])
    win = {("камень", "ножницы"), ("ножницы", "бумага"), ("бумага", "камень")}
    if user == bot:
        result = "Ничья"
    elif (user, bot) in win:
        result = "Ты победил 🎉"
    else:
        result = "Победил бот"
    g=_gdata(); taunt = random.choice(g["rps"]) if g["rps"] else ""
    await message.reply(
        card(
            "КНБ",
            f"Ты: <b>{user}</b>\nБот: <b>{bot}</b>\n\n<b>{result}</b>\n<i>{taunt[:80]}</i>",
            emoji="✂️",
            footer="/rps камень|ножницы|бумага",
        )
    )


@router.message(Command("guess", "угадай", "число"))
async def cmd_guess(message: Message, command: CommandObject):
    uid = message.from_user.id if message.from_user else 0
    arg = (command.args or "").strip().lower()
    if arg in ("new", "новая", "start", "старт", "") and not arg.isdigit():
        if arg in ("",) and uid in _guess:
            secret, tries = _guess[uid]
            await message.reply(
                card(
                    "Угадай число",
                    f"Игра уже идёт. Попыток: <b>{tries}</b>\n"
                    f"Пиши: <code>/guess 42</code>\n"
                    f"Новая: <code>/guess new</code>",
                    emoji="🔢",
                )
            )
            return
        secret = random.randint(1, 100)
        _guess[uid] = (secret, 0)
        await message.reply(
            card(
                "Угадай число",
                "Я загадал число от <b>1</b> до <b>100</b>.\n"
                "Пиши: <code>/guess 50</code>",
                emoji="🔢",
            )
        )
        return
    if uid not in _guess:
        secret = random.randint(1, 100)
        _guess[uid] = (secret, 0)
    if not arg.isdigit():
        await message.reply(fail("Нужно число: <code>/guess 50</code> или <code>/guess new</code>"))
        return
    n = int(arg)
    secret, tries = _guess[uid]
    tries += 1
    _guess[uid] = (secret, tries)
    if n < secret:
        hint = random.choice(_gdata()["guess"])[:60] if _gdata()["guess"] else ""
        await message.reply(card("Угадай число", f"<b>{n}</b> — мало. Попытка {tries}\n<i>{hint}</i>", emoji="🔢"))
    elif n > secret:
        hint = random.choice(_gdata()["guess"])[:60] if _gdata()["guess"] else ""
        await message.reply(card("Угадай число", f"<b>{n}</b> — много. Попытка {tries}\n<i>{hint}</i>", emoji="🔢"))
    else:
        del _guess[uid]
        await message.reply(
            ok(f"Верно! Число <b>{secret}</b> за <b>{tries}</b> попыток.\nЕщё раз: <code>/guess new</code>")
        )


