    arg = (command.args or "").strip()
    if not arg:
        sample = ", ".join(str(x) for x in sorted(RF_ARTICLES.keys())[:12])
        await message.reply(
            card(
                "Конституция РФ · статьи",
                "Показать статью:\n"
                f"› <code>/статья 19</code>\n"
                f"› <code>/article 49</code>\n\n"
                f"Доступны, например: {sample}…\n"
                f"Случайная: <code>/статья random</code>\n"
                f"Список номеров: <code>/статьи</code>",
                emoji="📜",
                footer="Краткие выдержки · не замена официальному тексту",
            )
        )
        return
    if arg.lower() in ("random", "rand", "случайная", "любая"):
        num = random.choice(list(RF_ARTICLES.keys()))
    elif arg.isdigit():
        num = int(arg)
    else:
        await message.reply(fail("Укажи номер: <code>/статья 19</code>"))
        return
    if num not in RF_ARTICLES:
        nearest = min(RF_ARTICLES.keys(), key=lambda x: abs(x - num))
        await message.reply(
            fail(
                f"Статьи <b>{num}</b> нет в подборке бота.\n"
                f"Ближайшая в базе: <code>/статья {nearest}</code>\n"
                f"Список: <code>/статьи</code>"
            )
        )
        return
    title, text = RF_ARTICLES[num]
    await message.reply(
        card(
            f"Статья {num} · {html_esc(title)}",
            html_esc(text),
            emoji="📜",
            footer="Конституция РФ · краткая выдержка · /статьи",
        )
    )


