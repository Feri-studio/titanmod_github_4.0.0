def severity_score(warns: int, mutes: int, bans: int) -> float:
    return warns * 1.0 + mutes * 2.5 + bans * 5.0

def suggest_action(score: float) -> str:
    if score < 2:
        return "warn"
    if score < 6:
        return "mute"
    if score < 12:
        return "tban"
    return "ban"

def clamp_rank(level: int) -> int:
    return max(0, min(7, int(level)))

def format_rank_line(level: int, name: str, emoji: str) -> str:
    return f"{emoji} [{level}] {name}"
