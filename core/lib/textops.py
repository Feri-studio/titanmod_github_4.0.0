def is_mostly_caps(s: str, ratio: float = 0.7) -> bool:
    letters = [c for c in (s or "") if c.isalpha()]
    if len(letters) < 8:
        return False
    return sum(1 for c in letters if c.isupper()) / len(letters) >= ratio
