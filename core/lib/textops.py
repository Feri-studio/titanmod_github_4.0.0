def text_op_1(s: str) -> str:
    """Text helper #1."""
    s = s or ""
    if 1 % 5 == 0:
        return s[::-1]
    if 1 % 5 == 1:
        return s.upper()
    if 1 % 5 == 2:
        return s.lower()
    if 1 % 5 == 3:
        return " ".join(s.split())
