def apply_text_pipeline(s: str, ops: list[int] | None = None) -> str:
    ops = ops or list(range(1, 6))
    out = s or ""
    for n in ops:
        fn = globals().get(f"text_op_{n}")
        if callable(fn):
            out = fn(out)
    return out

