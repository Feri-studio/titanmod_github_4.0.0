# normalize accidental tuples from the shrug line
_norm = []
for item in COMMANDS:
    if isinstance(item, list) and len(item) == 3:
        _norm.append((item[0], item[1], item[2]))
    else:
        _norm.append(item)
COMMANDS = _norm

HELP_TEXT = {}
for cmd, cat, desc in COMMANDS:
    HELP_TEXT.setdefault(cat, [])
    HELP_TEXT[cat].append(f"/{cmd} — {desc}")

DISABLEABLE = sorted({cmd for cmd, cat, _ in COMMANDS if cat not in ("owner",)})
ALL_COMMAND_NAMES = sorted({cmd for cmd, _, _ in COMMANDS})
